import type { summarizeModel } from "./report";

// Renders the README's results block from a committed eval run file. Pure: the
// script reads and writes files, this decides what the block says. Every number
// comes from the run file; nothing here is typed by hand.

export type ModelSummary = ReturnType<typeof summarizeModel>;

/** The parts of an evals/runs/<date>-eval.json file the README uses. */
export type EvalRunFile = {
  date: string;
  models: string[];
  reps: number;
  threshold: number;
  totalCostUsd: number;
  /** Written by npm run eval from 1 Nov 2026 on; older files don't have it. */
  pricesReadOn?: string;
  byModel: Record<string, ModelSummary>;
  runs: Array<{ file: string }>;
};

export const START = /<!-- eval:report:start(?: run=(\S+))? -->/;
export const END = "<!-- eval:report:end -->";

export class MissingMarkersError extends Error {
  constructor() {
    super(`README.md needs the markers <!-- eval:report:start run=<path> --> and ${END} around the results block.`);
    this.name = "MissingMarkersError";
  }
}

export function renderReport(run: EvalRunFile, runPath: string): string {
  const documents = new Set(run.runs.map((entry) => entry.file)).size;
  const facts = [
    `**Run ${run.date}**`,
    `${documents} ${documents === 1 ? "file" : "files"} × ${run.models.length} ${run.models.length === 1 ? "model" : "models"} × ${run.reps} ${run.reps === 1 ? "rep" : "reps"}`,
    `confidence threshold ${run.threshold}`,
    `run cost ${usd(run.totalCostUsd, 4)}`,
    ...(run.pricesReadOn ? [`prices read ${run.pricesReadOn}`] : []),
  ];

  const modelRows = run.models.map((model) => {
    const s = run.byModel[model];
    return row([
      `\`${model}\``,
      pct(s.accuracy),
      s.accuracyByRep.map((value) => (value * 100).toFixed(1)).join(" · "),
      String(s.silentErrorsPerDoc),
      String(s.caughtErrorsPerDoc),
      pct(s.hallucinatedRate),
      pct(s.firstTryValidRate, 0),
      `${s.needsHuman} of ${s.documents}`,
      usd(s.meanCostUsd, 5),
      seconds(s.p50LatencyMs),
      seconds(s.p95LatencyMs),
    ]);
  });

  // Worst first by whichever model did worst on the field, so no model's weak spot is buried.
  const keys = [...new Set(run.models.flatMap((model) => run.byModel[model].byKey.map((group) => group.key)))];
  const accuracyOf = (model: string, key: string) => run.byModel[model].byKey.find((group) => group.key === key);
  const worst = (key: string) => Math.min(...run.models.map((model) => accuracyOf(model, key)?.accuracy ?? 1));
  keys.sort((a, b) => worst(a) - worst(b) || a.localeCompare(b));
  const fieldRows = keys.map((key) =>
    row([
      `\`${key}\``,
      ...run.models.map((model) => {
        const group = accuracyOf(model, key);
        return group ? `${pct(group.accuracy)} (${group.correct}/${group.total})` : "—";
      }),
    ]),
  );

  return [
    `<!-- eval:report:start run=${runPath} -->`,
    `_Generated by \`npm run eval:report\` from [\`${runPath}\`](${runPath}). Edit the run, not this block._`,
    "",
    facts.join(" · "),
    "",
    row(["Model", "Field accuracy", "By rep (%)", "Silent errors / doc", "Caught errors / doc", "Hallucinated", "First-try valid", "Needs human", "Cost / doc", "p50", "p95"]),
    row(["---", ...Array(10).fill("---:")]),
    ...modelRows,
    "",
    "**Accuracy per field**, worst first",
    "",
    row(["Field", ...run.models.map((model) => `\`${model}\``)]),
    row(["---", ...run.models.map(() => "---:")]),
    ...fieldRows,
    END,
  ].join("\n");
}

/** The run path the README's start marker names, or null when it names none. */
export function readRunPath(readme: string): string | null {
  return START.exec(readme)?.[1] ?? null;
}

/** The README with its marked block swapped for `block`. Text outside the markers is untouched. */
export function replaceBlock(readme: string, block: string): string {
  const start = START.exec(readme);
  const end = readme.indexOf(END, start ? start.index : 0);
  if (!start || end < 0) throw new MissingMarkersError();
  return readme.slice(0, start.index) + block + readme.slice(end + END.length);
}

function row(cells: string[]): string {
  return `| ${cells.join(" | ")} |`;
}

function pct(value: number, digits = 1): string {
  return `${(value * 100).toFixed(digits)}%`;
}

function usd(value: number, digits: number): string {
  return `$${value.toFixed(digits)}`;
}

function seconds(ms: number): string {
  return `${(ms / 1000).toFixed(1)} s`;
}
